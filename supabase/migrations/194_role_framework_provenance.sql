-- Role intelligence: a generated role framework now records how much to trust it, and an AI-proposed alias can no longer silently merge two different job titles.
--
-- 1. careers gets a validation status (the lifecycle a framework moves through) and the provenance of its framework: role and competency confidence, source
--    coverage, what the independent reviewer said, what was dropped. career_skill_requirements records each skill's competency class, how it is assessed and why
--    the role needs it. All additive; curated roles keep working unchanged and count as PUBLISHED.
-- 2. match_careers no longer lets an alias the AI proposed score as a vouched-for name: it is capped below the "this is the role" threshold, so it is offered as a
--    suggestion the student must confirm. (This is what turned "Automobile Engineer" into "Automotive Engineer" without asking.)
-- 3. The roles already generated under the old single-pass prompt are marked AI_GENERATED, and the one reported as wrong is marked NEEDS_REVISION.
alter table public.careers
  add column if not exists validation_status text not null default 'PUBLISHED'
    check (validation_status in ('DRAFT','AI_GENERATED','UNDER_REVIEW','APPROVED','PUBLISHED','NEEDS_REVISION','ARCHIVED')),
  add column if not exists framework_version integer not null default 1,
  add column if not exists framework_meta jsonb;

alter table public.career_skill_requirements
  add column if not exists competency_class text check (competency_class is null or competency_class in ('CORE','INDUSTRY','TOOL','PRACTICAL','SUPPORTING','ANALYTICAL','ADVANCED')),
  add column if not exists assessment_type text,
  add column if not exists rationale text;

update public.careers set validation_status = 'AI_GENERATED', framework_version = 1,
  framework_meta = jsonb_build_object('frameworkVersion', 1, 'sourceCoverage', 'NONE', 'sources', '[]'::jsonb, 'needsHumanReview', true, 'verifiedByReviewerPass', false,
    'researchNote', 'Generated by the first, single-pass role prompt with no independent review and no external sources. Treat as provisional.')
where status = 'AI_GENERATED';

update public.careers set validation_status = 'NEEDS_REVISION',
  framework_meta = framework_meta || jsonb_build_object('revisionReason', 'Generated for "Automobile Engineer" but stored as "Automotive Engineer"; only one core skill and several generic skills. Rebuild with the reviewed pipeline.')
where key = 'ai-automotive-engineer';

create or replace function public.match_careers(p_query text, p_limit integer default 5)
 returns table(career_id uuid, key text, name text, status text, score real)
 language sql stable security definer
 set search_path to 'public', 'extensions'
as $function$
  with s as (
    select c.id, c.key, c.name, c.status, a.alias, a.source,
           greatest(similarity(a.alias, p_query),
                    case when p_query like '%' || a.alias || '%' and length(a.alias) >= 4 then 0.85 else 0 end,
                    case when a.alias like '%' || p_query || '%' and length(p_query) >= 4 then 0.7 else 0 end) as raw
    from public.career_aliases a join public.careers c on c.id = a.career_id and c.is_active
  )
  select s.id, s.key, s.name, s.status,
         max(case when s.source = 'AI' then least(s.raw, 0.6) else s.raw end)::real as score
  from s
  group by s.id, s.key, s.name, s.status
  having max(case when s.source = 'AI' then least(s.raw, 0.6) else s.raw end) > 0.2
  order by 5 desc limit p_limit
$function$;
