import { describe, expect, it } from "vitest";
import { validateTemplateSpec } from "@/lib/roadmap-visual/template-spec";
import { STARTER_METHOD, buildStarterSpec, isStarterProvenance, type StarterSkill } from "./starter";

const skill = (i: number, over: Partial<StarterSkill> = {}): StarterSkill => ({ name: `Skill ${i}`, category: i % 3 === 0 ? "Tools" : "Concepts", description: null, importance: i < 4 ? "CRITICAL" : i < 10 ? "HIGH" : i < 16 ? "MEDIUM" : "LOW", targetLevel: 60 + (i % 20), ...over });
const skills = Array.from({ length: 24 }, (_, i) => skill(i));
const spec = buildStarterSpec({ careerKey: "data-analyst", careerName: "Data Analyst", version: 3, skills });
const ref = { skills: { statusByName: new Map(skills.map((s) => [s.name, "active" as const])) }, careers: new Map([["data-analyst", "id"]]) };

describe("buildStarterSpec", () => {
  it("is a valid roadmap for the role, with one topic per skill", () => {
    const v = validateTemplateSpec(spec, ref);
    expect(v.errors).toEqual([]);
    expect(v.ok).toBe(true);
    expect(spec.nodes.filter((n) => n.type === "TOPIC")).toHaveLength(24);
    expect(spec.version).toBe(3);
  });
  it("spreads the skills over all four stages, most important first", () => {
    const stageOf = (name: string) => spec.nodes.find((n) => n.skill === name)!.stage;
    expect(new Set(spec.nodes.filter((n) => n.type === "TOPIC").map((n) => n.stage)).size).toBe(4);
    expect(stageOf("Skill 0")).toBe("FOUNDATION");
    expect(stageOf("Skill 23")).toBe("JOB_READY");
  });
  it("carries each skill's importance and target, and groups by category", () => {
    const t = spec.nodes.find((n) => n.skill === "Skill 0")!;
    expect(t).toMatchObject({ importance: "CORE", target: 60 });
    expect(spec.nodes.find((n) => n.skill === "Skill 23")!.importance).toBe("OPTIONAL");
    const group = spec.nodes.find((n) => n.key === t.parent)!;
    expect(group.type).toBe("GROUP");
    expect(group.title).toBe("Tools");
  });
  it("keeps topic keys derived from the skill, so a later full roadmap keeps the student's marks", () => {
    expect(spec.nodes.find((n) => n.skill === "Skill 7")!.key).toBe("skill-7");
  });
  it("says what it is", () => {
    expect(spec.title).toMatch(/starter/i);
    expect(isStarterProvenance(spec.provenance)).toBe(true);
    expect(isStarterProvenance({ method: "Generated by an AI model" })).toBe(false);
    expect(STARTER_METHOD.length).toBeGreaterThan(10);
  });
  it("copes with a small role and a skill with no category", () => {
    const small = buildStarterSpec({ careerKey: "x-role", careerName: "X", version: 1, skills: [skill(0, { category: null }), skill(1), skill(2)] });
    expect(validateTemplateSpec(small, { skills: { statusByName: new Map([["Skill 0", "active"], ["Skill 1", "active"], ["Skill 2", "active"]]) }, careers: new Map([["x-role", "id"]]) }).errors).toEqual([]);
  });
});
